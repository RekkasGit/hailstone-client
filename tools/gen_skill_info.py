#!/usr/bin/env python3
"""Writes src/game/mechanics/skill_info.inc (per-skill flags of the original
client's skill table) from CSkillMgr_InitSkillTable @0x4a7930, as a table
extracted from the exe (SKILL_TABLE_INC: one row of InitSkillTable's stores per skill).

InitSkillTable first resets every skill (LevelCappedSkill = true,
Activated = false, Available[c] = 255) and then runs two switches on the skill
id: the case stores, then a shared tail. Only the fields the mechanics need
are emitted: LevelCappedSkill (+0x21, read by CSkillMgr::GetSkillCap @0x5baec0),
Activated (+0x20) and the name's eqstr id (nName, +8).

usage: tools/gen_skill_info.py SKILL_TABLE_INC > src/game/mechanics/skill_info.inc
"""
import re
import sys

text = open(sys.argv[1], encoding="utf-8").read()
# The first switch only (the shared tail stores Available[] alone).
first = text.split("switch (id) {")[1]


def cases(block):
    """Maps each skill id (or 'default') to its statements."""
    out = {}
    labels = []
    body = []
    for line in block.split("\n"):
        s = line.strip()
        if s.startswith("case ") or s == "default:":
            if body and labels:
                for l in labels:
                    out[l] = body
                labels, body = [], []
            if s == "default:":
                labels.append("default")
            else:
                labels += [int(x) for x in re.findall(r"case (\d+):", s)]
            continue
        if s == "break;" or s.startswith("}"):
            if labels:
                for l in labels:
                    out[l] = body
            labels, body = [], []
            if s.startswith("}"):
                break
            continue
        body.append(s)
    return out


table = cases(first)
rows = []
for skill in range(100):
    capped, activated, name = True, False, 0
    for stmt in table.get(skill, table["default"]):
        for part in stmt.split(";"):
            part = part.strip()
            if part == "skill->LevelCappedSkill = false":
                capped = False
            elif part == "skill->Activated = true":
                activated = True
            m = re.match(r"skill->nName = (\d+)", part)
            if m:
                name = int(m.group(1))
    rows.append((skill, capped, activated, name))

print("// Generated by tools/gen_skill_info.py from the original\'s skill table")
print("// (CSkillMgr_InitSkillTable @0x4a7930). Do not edit.")
print("// HAILSTONE_SKILL(id, LevelCappedSkill, Activated, name eqstr)")
for skill, capped, activated, name in rows:
    print(f"HAILSTONE_SKILL({skill}, {'true' if capped else 'false'}, {'true' if activated else 'false'}, {name})")
