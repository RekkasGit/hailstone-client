#!/usr/bin/env python3
"""Writes src/game/zone_names.inc (zone id, short name, long name, zone flags, expansion) from the
original client's zone table as extracted by rof2decomp
(rof2decomp:re/src/game/world/zone_table.inc, from ZoneManager::ZoneManager @0x7dca10).

usage: tools/gen_zone_names.py ROF2DECOMP_ZONE_TABLE_INC > src/game/zone_names.inc
"""
import re
import sys

rows = []
seen = set()
for line in open(sys.argv[1], encoding="utf-8"):
    m = re.match(r"\s*(ZONE_\w+)\(([^)]*)\)\s*//\s*(\S+)\s+(.*)$", line)
    if not m:
        continue
    kind = m.group(1)
    args = [a.strip() for a in m.group(2).split(",")]
    zone_id = int(args[2], 0)
    # Both registration paths fill only an empty slot (RegisterZone2 @0x7dc430, the inlined copies), so the
    # first row of an id is the one the client keeps (arena: classic before its LDoN row).
    if zone_id in seen:
        continue
    seen.add(zone_id)
    # EQZoneInfo +8, EQWorldData::ExpansionZone @0x7dc510: the argument before the id.
    expansion = int(args[1], 0)
    # The zone's flags (EQZoneInfo +0x198): after the string id, past RegisterZone2's two extra arguments.
    flags = int(args[8 if kind == "ZONE_ADD_EX" else 6], 0)
    short, long_name = m.group(3), m.group(4).strip()
    rows.append((zone_id, short, long_name.replace("\\", "\\\\").replace('"', '\\"'), flags, expansion))

print("// Generated by tools/gen_zone_names.py from rof2decomp's extraction of the original")
print("// client's zone table (ZoneManager::ZoneManager @0x7dca10). Do not edit by hand.")
print(f"// {len(rows)} zones.")
for zone_id, short, long_name, flags, expansion in sorted(rows):
    print(f'NMSC_ZONE({zone_id}, "{short}", "{long_name}", {flags:#x}, {expansion})')
