#!/usr/bin/env python3
"""Writes src/game/slash_commands.inc from the original client's command
table (__CommandList @0x00acd5a8, CMDLIST[392]) as extracted by rof2decomp
(rof2decomp:symbols/slash_commands_ui2.csv).

The voice macro commands (/vplay, /vtell, /vgroup, /vraid: Cmd_vplay and the three Send_OP_VoiceMacroIn handlers)
are left out on purpose: Hailstone does not implement voice macros, so those words answer as unknown commands. So
are the commands of Daybreak's services EQEmu has no part of: /achievements and /tcg (the Legends of Norrath card
game). /marketplace, /realestate and /leaverealestate stay: a server that runs a store or housing answers them.
/mp3 is left out too: Hailstone has no music player for the player's own files.

usage: tools/gen_slash_commands.py ROF2DECOMP_SLASH_COMMANDS_CSV > src/game/slash_commands.inc
"""
import csv
import sys

# Handlers of features this client leaves out (see the docstring).
DROPPED = ("Cmd_vplay", "Send_OP_VoiceMacroIn_", "Cmd_achievements", "Cmd_legendsofnorrath", "Cmd_mp3")

rows = []
with open(sys.argv[1], newline="", encoding="utf-8") as f:
    for r in csv.DictReader(f):
        name = r["name"]
        if not name.strip():
            continue  # the table's terminator
        if r["handler_name"].startswith(DROPPED):
            continue
        rows.append((int(r["index"]), name, int(r["eqstr_id"]), r["handler_name"], int(r["restriction"]),
                     int(r["category"]), int(r["flags"])))

print("// Generated by tools/gen_slash_commands.py from rof2decomp:symbols/slash_commands_ui2.csv")
print("// (the original's __CommandList @0x00acd5a8, in table order, without the commands left out on purpose).")
print("// Do not edit by hand.")
print("// NMSC_SLASH(name, eqstr id of the localised name (-1 none), original handler, restriction,")
print("//            /help category, flags)")
print(f"// {len(rows)} commands.")
for _, name, eqstr, handler, restriction, category, flags in sorted(rows):
    esc = name.replace("\\", "\\\\").replace('"', '\\"')
    print(f'NMSC_SLASH("{esc}", {eqstr}, "{handler}", {restriction}, {category}, {flags})')
