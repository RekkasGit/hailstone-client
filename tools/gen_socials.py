#!/usr/bin/env python3
"""Writes src/game/socials.inc: the social emotes of CEverQuest::send_social
@0x526910 in the original eqgame.exe, read from its two jump tables (the
text others see @0x52ab9c, the player's own echo @0x52acfc). For each of the
88 socials: the animation (OP_Animation action, -1 none) and, per table, the
eqstr template without a target and with one, with the argument slots each
template takes:
  n  the subject (others: empty, the server prefixes the name; echo: "You")
  t  the target's name
  s/o/p  the player's he/him/his (echo: you/you/your)
  S/O/P  the target's he/him/his

Also writes the command → social id map, read from COMMANDS_DIR's listing of
the command handlers (socials.inc and standing_socials.cpp), as
HAILSTONE_SOCIAL_COMMAND(handler, id, needs standing still).

usage: tools/gen_socials.py PATH/TO/eqgame.exe COMMANDS_DIR > src/game/socials.inc
"""
import re
import struct
import subprocess
import sys

EXE = sys.argv[1]
data = open(EXE, "rb").read()
pe = struct.unpack_from("<I", data, 0x3C)[0]
nsec = struct.unpack_from("<H", data, pe + 6)[0]
opt = struct.unpack_from("<H", data, pe + 20)[0]
base = struct.unpack_from("<I", data, pe + 24 + 28)[0]
secs = []
for i in range(nsec):
    o = pe + 24 + opt + 40 * i
    vs, va, rs, ro = struct.unpack_from("<IIII", data, o + 8)
    secs.append((base + va, base + va + rs, ro))


def read(v, n):
    for lo, hi, ro in secs:
        if lo <= v < hi:
            return data[ro + v - lo : ro + v - lo + n]
    raise ValueError(hex(v))


dis = subprocess.run(["objdump", "-d", "-M", "intel", "--no-show-raw-insn", "--start-address=0x526910",
                      "--stop-address=0x52ab9c", EXE], capture_output=True, text=True, check=True).stdout
ins = []
for line in dis.splitlines():
    m = re.match(r"\s*([0-9a-f]+):\s+(.*)$", line)
    if m:
        ins.append((int(m.group(1), 16), m.group(2).strip()))
index = {a: i for i, (a, _) in enumerate(ins)}

# Frame offsets of the argument buffers (esp after the prologue's pushes).
SLOTS = {0x10: "n", 0x50: "t", 0x15C: "s", 0x39C: "o", 0x11C: "p", 0x45C: "S", 0x3DC: "O", 0x41C: "P"}
UNTARGETED, TARGETED = 0x90, 0x19C


def simulate(start, bias):
    """Walks one case: BuildStringFromEQSTR (0x4edfa0) calls and the animation store."""
    i = index[start]
    depth, regs, pushes, calls, anim = bias, {}, [], {}, -1
    for _ in range(400):
        _, t = ins[i]
        m = re.match(r"push\s+(\S+)$", t)
        if m:
            arg = m.group(1)
            depth += 4
            pushes.append(int(arg, 16) if arg.startswith("0x") else ("buf", regs[arg]) if arg in regs else None)
            i += 1
            continue
        m = re.match(r"lea\s+(\w+),\[esp\+0x([0-9a-f]+)\]", t)
        if m:
            regs[m.group(1)] = int(m.group(2), 16) - depth
            i += 1
            continue
        m = re.match(r"mov\s+DWORD PTR \[esp\+0x([0-9a-f]+)\],0x([0-9a-f]+)", t)
        if m and int(m.group(1), 16) - depth == 0xC:
            anim = int(m.group(2), 16)
        if t.startswith("call   0x4edfa0"):
            args = pushes[-11:][::-1]  # out, id, %1..%9
            out = args[0][1]
            slots = "".join(SLOTS[a[1]] for a in args[2:] if isinstance(a, tuple))
            calls[out] = (args[1], slots)
            i += 1
            continue
        if t.startswith("add    esp"):
            break
        m = re.match(r"jmp\s+0x([0-9a-f]+)$", t)
        if m:
            i = index[int(m.group(1), 16)]
            continue
        i += 1
    return calls, anim


def table(address):
    raw = read(address, 4 * 0x58)
    return [struct.unpack_from("<I", raw, 4 * k)[0] for k in range(0x58)]


print("// Generated by tools/gen_socials.py from the original eqgame.exe (CEverQuest::send_social")
print("// @0x526910, jump tables @0x52ab9c and @0x52acfc). Do not edit by hand.")
print("// HAILSTONE_SOCIAL(id, animation, others: untargeted eqstr, slots, targeted eqstr, slots,")
print("//             echo: untargeted eqstr, slots, targeted eqstr, slots); slots: see the script.")
for k, (a, b) in enumerate(zip(table(0x52AB9C), table(0x52ACFC))):
    if a == 0x52AB8D:
        continue
    others, anim = simulate(a, 0)
    echo, _ = simulate(b, 4)  # the echo switch runs with one more dword pushed
    ou, ot = others.get(UNTARGETED, (0, "")), others.get(TARGETED, (0, ""))
    eu, et = echo.get(UNTARGETED, (0, "")), echo.get(TARGETED, (0, ""))
    print(f'HAILSTONE_SOCIAL({k}, {anim if anim != -1 else -1}, {ou[0]}, "{ou[1]}", {ot[0]}, "{ot[1]}", '
          f'{eu[0]}, "{eu[1]}", {et[0]}, "{et[1]}")')

cmds = []
for line in open(sys.argv[2] + "/socials.inc", encoding="utf-8"):
    m = re.match(r"ROF2_SOCIAL_COMMAND\((\w+), 0x[0-9a-f]+, (0x[0-9a-f]+)\)", line)
    if m:
        cmds.append((m.group(1), int(m.group(2), 16), 0))
for m in re.finditer(r"void __cdecl (\w+)\(void \*, const char \*args\) \{\s*StandingSocial\(args, (0x[0-9a-f]+|\d+)\);",
                     open(sys.argv[2] + "/standing_socials.cpp", encoding="utf-8").read()):
    cmds.append((m.group(1), int(m.group(2), 0), 1))
for name, sid, standing in sorted(cmds, key=lambda c: c[1]):
    print(f'HAILSTONE_SOCIAL_COMMAND("{name}", {sid}, {standing})')
