#!/usr/bin/env python3
"""Writes src/game/keymap_tables.inc: the original client's key binding tables.

Sources (all from rof2decomp, the behaviour spec):
  - the mappable command names, szEQMappableCommands at 0xad7750 in NMS/eqgame.exe (479 names; the
    ini key of a command is KEYMAPPING_<name>_<1|2>, KeypressHandler::GetEqCommandSaveName @0x5596f0);
  - the default bindings KeypressHandler::ResetKeysToEqDefaults @0x5598d0 sets
    (re/src/game/ui/default_keys.inc, generated by tools/re/gen_default_keys.py): slot offsets into
    the two banks of 500 KeyCombos (+0 and +0x7d0), and the KeyCombo int (scan code | 0x40000000
    shift | 0x20000000 ctrl | 0x10000000 alt);
  - the legacy KEYMAP_<name> text format's tables (KeypressHandler_ReadKeyMapFromIni @0x513940):
    47 {char, code} at 0xad7f10 and 54 {code, name} at 0xad8088;
  - the key names KeyCombo::GetTextDescription @0x88b690 appends (re/src/game/ui/key_names.inc:
    scan code and the exe address of the text);
  - the keyboard assignment labels and categories COptionsWnd::InitKeyboardAssignments @0x7046c0 sets
    (re/src/game/ui/keyboard_assignments.inc: entry offset 0x40c + 8 * command, eqstr id, category).

usage: tools/gen_keymap.py ROF2DECOMP_DIR > src/game/keymap_tables.inc
"""
import os
import re
import struct
import sys

import pefile

root = sys.argv[1]
pe = pefile.PE(os.path.join(root, "NMS/eqgame.exe"))
base = pe.OPTIONAL_HEADER.ImageBase


def data(addr, n):
    return pe.get_data(addr - base, n)


def cstr(addr):
    d = data(addr, 128)
    return d[: d.index(0)].decode("latin1")


COMMANDS = 0x1DF  # 479: KeypressHandler::LoadAndSetKeymappings walks 0..0x1de
names = [cstr(struct.unpack("<I", data(0xAD7750 + 4 * i, 4))[0]) for i in range(COMMANDS)]
for n in names:
    assert re.fullmatch(r"[A-Z][A-Z0-9_]*", n), n

out = []
out.append("// Generated by tools/gen_keymap.py from rof2decomp (NMS/eqgame.exe tables and")
out.append("// re/src/game/ui/{default_keys,key_names,keyboard_assignments}.inc). Do not edit.")
out.append("#ifdef HAILSTONE_KEY_COMMAND")
out.append("// HAILSTONE_KEY_COMMAND(index, NAME): szEQMappableCommands @0xad7750")
for i, n in enumerate(names):
    out.append(f"HAILSTONE_KEY_COMMAND({i}, {n})")
out.append("#endif")

out.append("#ifdef HAILSTONE_KEY_DEFAULT")
out.append("// HAILSTONE_KEY_DEFAULT(set, bank, slot, code): ResetKeysToEqDefaults @0x5598d0 in call order;")
out.append("// set 0 UseWASDDefault, 1 arrows, 2 everyone, 3 when 0xddfd54 == 3. Slots >= 479 have no command name.")
sets = {"KEY_WASD": 0, "KEY_ARROWS": 1, "KEY_ALL": 2, "KEY_CLASS3": 3}
for line in open(os.path.join(root, "re/src/game/ui/default_keys.inc")):
    m = re.match(r"(KEY_\w+)\((0x[0-9a-f]+), (0x[0-9a-f]+)\)", line)
    if not m:
        continue
    off, code = int(m.group(2), 16), int(m.group(3), 16)
    bank = 1 if off >= 0x7D0 else 0
    slot = (off - 0x7D0 * bank) // 4
    out.append(f"HAILSTONE_KEY_DEFAULT({sets[m.group(1)]}, {bank}, {slot}, 0x{code:08x})")
out.append("#endif")

out.append("#ifdef HAILSTONE_KEY_CHAR")
out.append("// HAILSTONE_KEY_CHAR(char, scan code): 0xad7f10, the one-character key names of KEYMAP_ values")
for i in range(0x2F):
    ch, code = struct.unpack("<cxxxI", data(0xAD7F10 + 8 * i, 8))
    c = ch.decode("latin1")
    lit = "'\\\\'" if c == "\\" else "'\\''" if c == "'" else f"'{c}'"
    out.append(f"HAILSTONE_KEY_CHAR({lit}, 0x{code:02x})")
out.append("#endif")

out.append("#ifdef HAILSTONE_KEY_NAMED")
out.append("// HAILSTONE_KEY_NAMED(code, \"NAME\"): 0xad8088, the named keys of KEYMAP_ values (code -1: NOKEY)")
for i in range(0x36):
    code, p = struct.unpack("<iI", data(0xAD8088 + 8 * i, 8))
    out.append(f"HAILSTONE_KEY_NAMED({code}, \"{cstr(p)}\")")
out.append("#endif")

out.append("#ifdef HAILSTONE_KEY_TEXT")
out.append("// HAILSTONE_KEY_TEXT(scan code, \"text\"): the names KeyCombo::GetTextDescription @0x88b690 appends")
for line in open(os.path.join(root, "re/src/game/ui/key_names.inc")):
    m = re.match(r"KEY_NAME\((0x[0-9a-f]+), (0x[0-9a-f]+)\)", line)
    if m:
        out.append(f"HAILSTONE_KEY_TEXT({m.group(1)}, \"{cstr(int(m.group(2), 16))}\")")
out.append("#endif")

out.append("#ifdef HAILSTONE_KEY_LABEL")
out.append("// HAILSTONE_KEY_LABEL(command, eqstr id, category): COptionsWnd::InitKeyboardAssignments @0x7046c0")
for line in open(os.path.join(root, "re/src/game/ui/keyboard_assignments.inc")):
    m = re.match(r"KA_ENTRY\((0x[0-9a-f]+), (0x[0-9a-f]+), (0x[0-9a-f]+)\)", line)
    if m:
        off, sid, cat = (int(x, 16) for x in m.groups())
        out.append(f"HAILSTONE_KEY_LABEL({(off - 0x40C) // 8}, {sid}, 0x{cat:x})")
out.append("#endif")
print("\n".join(out))
