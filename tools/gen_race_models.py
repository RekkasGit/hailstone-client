#!/usr/bin/env python3
"""Writes src/game/race_models.inc: the original client's race/gender -> model
code table, and the classic animation-sharing table.

Sources:
- rof2decomp:symbols/race_models_spawn.csv, extracted from the RoF2 client's
  model table (NpcManager_GetModelCode @0050a2d0, filled by the AddRaceGender
  calls listed in the CSV; notes/spawns-races-models.md section 5.1).
- tools/data/lantern_animationsources.txt, LanternExtractor's (MIT) list of
  which classic models borrow animation clips from another model.
- tools/data/rof2_animation_sources.txt, the donors the RoF2 client's
  ActorAnimation::GetAlternateAnimTag (0x406a60) names that Lantern's list
  leaves out (the female froglok FRF -> FRM among them).

usage: tools/gen_race_models.py RACE_MODELS_SPAWN_CSV tools/data/lantern_animationsources.txt \
           tools/data/rof2_animation_sources.txt > src/game/race_models.inc
"""
import csv
import re
import sys

rows = []
for r in csv.DictReader(open(sys.argv[1], encoding="utf-8")):
    code = r["model_code"].strip()
    if not re.fullmatch(r"[A-Za-z0-9_]+", code):
        continue
    rows.append((int(r["race"]), int(r["gender"]), code.upper(), int(r["flags_0x2c"], 16),
                 int(r["anim_fallback_race_0x28"])))

donors = []
for path in sys.argv[2:]:
    for line in open(path, encoding="utf-8"):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        model, donor = (s.strip().upper() for s in line.split(",", 1))
        if any(m == model for m, _ in donors):
            continue  # the first file's row stands
        donors.append((model, donor))

print("// Generated by tools/gen_race_models.py. Do not edit by hand.")
print("// HAILSTONE_RACE_MODEL(race, gender, code, flags, anim_fallback): the RoF2 client's model table")
print("// (rof2decomp symbols/race_models_spawn.csv, NpcManager_GetModelCode @0050a2d0).")
print("// Gender 0 male, 1 female, 2 neutral. flags = record+0x2c (0x08 new-style model,")
print("// 0x04 has an animation fallback race = record+0x28).")
print(f"// {len(rows)} rows, {len({r[0] for r in rows})} race ids.")
for race, gender, code, flags, fallback in sorted(rows):
    print(f'HAILSTONE_RACE_MODEL({race}, {gender}, "{code}", 0x{flags:x}, {fallback})')
print()
print("// HAILSTONE_ANIM_SOURCE(model, donor): classic models that borrow clips from another")
print("// model (LanternExtractor ClientData/animationsources.txt, MIT; then the RoF2 client's")
print("// GetAlternateAnimTag @0x406a60 for the codes it leaves out).")
print(f"// {len(donors)} rows.")
for model, donor in donors:
    print(f'HAILSTONE_ANIM_SOURCE("{model}", "{donor}")')
