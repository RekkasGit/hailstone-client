#!/usr/bin/env python3
"""Writes src/game/mechanics/skill_timers.inc: the reuse timer, base damage and
combat type of each skill in the original client's skill table
(CSkillMgr_InitSkillTable @0x4a7930), from a table extracted from the exe
(SKILL_TABLE_INC: one row of InitSkillTable's stores per skill).

InitSkillTable resets ReuseTimer, BaseDamage and SkillCombatType to 0 and then
stores the skill's own values in its first switch. The fields are the ones
CSkillMgr::GetReuseTime @0x5bab70 (+0xc), CSkillMgr::GetBaseDamage @0x5bab40
(+0x10) and CSkillMgr_GetSkillCombatType @0x5baae0 (+0x14) return.

usage: tools/gen_skill_timers.py SKILL_TABLE_INC > src/game/mechanics/skill_timers.inc
"""
import re
import sys

text = open(sys.argv[1], encoding="utf-8").read()
first = text.split("switch (id) {")[1]

table, labels, body = {}, [], []
for line in first.split("\n"):
    s = line.strip()
    if s.startswith("case ") or s == "default:":
        if body and labels:
            for l in labels:
                table[l] = body
            labels, body = [], []
        labels += ["default"] if s == "default:" else [int(x) for x in re.findall(r"case (\d+):", s)]
        continue
    if s == "break;" or s.startswith("}"):
        for l in labels:
            table[l] = body
        labels, body = [], []
        if s.startswith("}"):
            break
        continue
    body.append(s)

print("// Generated by tools/gen_skill_timers.py from the original\'s skill table")
print("// (CSkillMgr_InitSkillTable @0x4a7930). Do not edit.")
print("// HAILSTONE_SKILL_TIMER(id, ReuseTimer ms, BaseDamage, SkillCombatType)")
for skill in range(100):
    reuse = damage = combat = 0
    for stmt in table.get(skill, table["default"]):
        for part in stmt.split(";"):
            part = part.strip()
            m = re.match(r"skill->(ReuseTimer|BaseDamage|SkillCombatType) = (-?\d+)", part)
            if m:
                v = int(m.group(2))
                if m.group(1) == "ReuseTimer":
                    reuse = v
                elif m.group(1) == "BaseDamage":
                    damage = v
                else:
                    combat = v
    print(f"HAILSTONE_SKILL_TIMER({skill}, {reuse}, {damage}, {combat})")
