#!/usr/bin/env python3
"""Writes ui/classic/lib/nowrap.lua: the Labels of the stock EQUI_*.xml files that have <NoWrap>true</NoWrap>.
SIDL's Label defaults NoWrap to false and CLabelWnd's draw (@0x88e110) wraps its text unless bNoWrap is set
(CTextureFont::DrawWrappedText2 flag 1), so lib/sidl.lua wraps every other label. Label item names are unique across
the stock files, so the table is keyed by item name (the layouts' `name`).

usage: tools/gen_label_nowrap.py <game dir>/uifiles/default > ui/classic/lib/nowrap.lua
"""
import glob
import os
import re
import sys

names = set()
for path in sorted(glob.glob(os.path.join(sys.argv[1], "*.xml"))):
    text = open(path, encoding="latin-1").read()
    for m in re.finditer(r'<Label\s+item\s*=\s*"([^"]*)"\s*>(.*?)</Label>', text, re.S):
        if "<NoWrap>true</NoWrap>" in m.group(2):
            names.add(m.group(1))

print("-- Generated by tools/gen_label_nowrap.py from the stock uifiles/default/*.xml. Do not edit.")
print("-- The Labels with <NoWrap>true</NoWrap> (every other label wraps its text, as CLabelWnd draws it).")
print("return {")
for n in sorted(names):
    print(f'  ["{n}"] = true,')
print("}")
